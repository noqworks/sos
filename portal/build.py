#!/usr/bin/env python3
"""Build the two on-device pages of noq_sos.

Setup page (Wi-Fi):   index.html + tokens.css + components.css + app.js + logo.svg -> portal_page.h (PAGE_GZ)
NOQ SOS page:         panel.html + tokens.css + components.css + panel.css + panel.js + logo.svg -> panel_page.h (PANEL_GZ)
Home screen icon:     icon.png (192 × 192, the NOQopen mark) -> icon_png.h (ICON_PNG), served at /icon.png

Each page is inlined into one HTML file, gzipped and written as a C header. Run after editing anything in portal/:

    python3 portal/build.py              # writes both headers
    python3 portal/build.py --html DIR   # also writes the inlined pages (index.html, panel.html) for a browser preview
    python3 portal/build.py --check      # fails if a header is not built from the current sources (CI)
"""
import gzip
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
COMPONENT = ROOT.parent / "components" / "noq_sos"
PAGES = (
    # (html, extra css, js, header, C symbol)
    ("index.html", (), "app.js", "portal_page.h", "PAGE_GZ"),
    ("panel.html", ("panel.css",), "panel.js", "panel_page.h", "PANEL_GZ"),
)


def css(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"\s+", " ", text)
    text = re.sub(r"\s*([{};,>])\s*", r"\1", text)
    return text.replace(";}", "}").strip()


def js(text: str) -> str:
    lines = [ln.strip() for ln in text.splitlines()]
    return "\n".join(ln for ln in lines if ln and not ln.startswith("//"))


def logo(text: str) -> str:
    text = re.sub(r"<\?xml.*?\?>", "", text)
    text = re.sub(r"<defs>.*?</defs>", "", text, flags=re.S)
    text = re.sub(r'\s(id|data-name)="[^"]*"', "", text)
    text = text.replace('class="cls-1"', 'fill="#a3e635"')
    text = text.replace("<svg ", '<svg class="np-logo" aria-hidden="true" ', 1)
    text = re.sub(r">\s+<", "><", text)
    return text.strip()


def read(name: str) -> str:
    return (ROOT / name).read_text(encoding="utf-8")


def page(html_name: str, extra_css: tuple, js_name: str) -> str:
    html = read(html_name)
    style = css("".join(read(n) for n in ("tokens.css", "components.css", *extra_css)))
    html = html.replace("/*CSS*/", style)
    html = html.replace("<!--LOGO-->", logo(read("logo.svg")))
    html = html.replace("/*JS*/", js(read(js_name)))
    return re.sub(r">\s+<", "><", html).strip()


def header(data: bytes, symbol: str) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    body = ",\n    ".join(rows)
    return (
        "#pragma once\n"
        "// Generated by portal/build.py. Do not edit; change portal/ and rebuild.\n\n"
        '#include "esphome/core/hal.h"\n\n'
        "namespace esphome::noq_sos {\n\n"
        f"constexpr uint8_t {symbol}[] PROGMEM = {{\n    {body}}};\n\n"
        "}  // namespace esphome::noq_sos\n"
    )


def icon_header(data: bytes) -> str:
    return header(data, "ICON_PNG").replace("Do not edit; change portal/ and rebuild.", "Do not edit; replace portal/icon.png and rebuild.")


def committed(out: pathlib.Path) -> str:
    if not out.exists():
        return ""
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", out.read_text(encoding="utf-8")))
    return gzip.decompress(data).decode("utf-8")


def main() -> None:
    stale = []
    for html_name, extra_css, js_name, header_name, symbol in PAGES:
        html = page(html_name, extra_css, js_name)
        out = COMPONENT / header_name
        if "--check" in sys.argv:
            if committed(out) != html:
                stale.append(header_name)
            continue
        data = gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)
        out.write_text(header(data, symbol), encoding="utf-8")
        if "--html" in sys.argv:
            target = pathlib.Path(sys.argv[sys.argv.index("--html") + 1])
            target.mkdir(parents=True, exist_ok=True)
            (target / html_name).write_text(html, encoding="utf-8")
        print(f"{html_name}: {len(html)} bytes html, {len(data)} bytes gzip -> {out.relative_to(ROOT.parent)}")
    icon = (ROOT / "icon.png").read_bytes()
    icon_out = COMPONENT / "icon_png.h"
    if "--check" in sys.argv:
        if not icon_out.exists() or icon_out.read_text(encoding="utf-8") != icon_header(icon):
            stale.append("icon_png.h")
    else:
        icon_out.write_text(icon_header(icon), encoding="utf-8")
        print(f"icon.png: {len(icon)} bytes -> {icon_out.relative_to(ROOT.parent)}")
    if "--check" in sys.argv:
        if stale:
            sys.exit(f"{', '.join(stale)} out of date: run python3 portal/build.py and commit")
        print("page headers are up to date")


if __name__ == "__main__":
    main()
